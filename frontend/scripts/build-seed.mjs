#!/usr/bin/env node
/**
 * Writes src/seeds/basket.css: basket's palette, derived from one colour (Violet #7c3aed) by the
 * @lifekit-hq/tokens seed engine, in the same shape as the seeds the package ships for its own apps.
 *
 *   node scripts/build-seed.mjs           rewrite the file
 *   node scripts/build-seed.mjs --check   exit 1 when the file is out of step with the engine
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

import {derive, DEFAULT_INTENSITY, toCss} from '@lifekit-hq/tokens/engine';

export const SEED = '#7c3aed';
const OUT = fileURLToPath(new URL('../src/seeds/basket.css', import.meta.url));

const LIGHT = ":root,\n[data-theme='light']";
const DARK = "[data-theme='dark']";

function palette(mode, contrast) {
  return derive({seed: SEED, intensity: DEFAULT_INTENSITY, mode, contrast}).tokens;
}

export function render() {
  return [
    '/*',
    ` * Basket seed theme: seed ${SEED} (Violet), intensity ${DEFAULT_INTENSITY}.`,
    ' * Generated by scripts/build-seed.mjs from @lifekit-hq/tokens/engine; do not edit. Import after theme.css.',
    ' */',
    '',
    ':root {',
    `  --app-seed: ${SEED};`,
    '}',
    '',
    toCss(LIGHT, palette('light', 'standard')),
    '',
    toCss(DARK, palette('dark', 'standard')),
    '',
    '@media (prefers-contrast: more) {',
    toCss(LIGHT, palette('light', 'more'), '  '),
    '',
    toCss(DARK, palette('dark', 'more'), '  '),
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      /* missing file counts as out of step */
    }
    if (current !== next) {
      console.error('build-seed: src/seeds/basket.css is out of step; run `npm run build:seed`');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
    console.log('build-seed: wrote src/seeds/basket.css');
  }
}
